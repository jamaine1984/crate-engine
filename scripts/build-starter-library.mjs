// Builds the Starter Library catalog from starter-library/picks.json.
// The library is three animated characters. Their GLB files live in the repo at
// starter-library/models/<path>.glb and are served from the site itself (no outside asset host).
// Writes starter-library/catalog.json (read by the editor) and starter-library/catalog.mjs (read by the AI connector).
// Usage: node scripts/build-starter-library.mjs
import { readFile, writeFile, access } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const libDir = path.join(rootDir, 'starter-library');

const picks = JSON.parse(await readFile(path.join(libDir, 'picks.json'), 'utf8'));
const entries = [];
for (const modelPath of picks.keep) {
  const file = path.join(libDir, 'models', `${modelPath}.glb`);
  const bytes = await readFile(file).catch(() => { throw new Error(`${modelPath}: missing ${file}`); });
  if (bytes.toString('latin1', 0, 4) !== 'glTF' || bytes.readUInt32LE(4) !== 2) throw new Error(`${modelPath}: not a glTF 2.0 binary`);
  const thumbName = modelPath.replace(/[^a-z0-9]+/gi, '_').toLowerCase() + '.webp';
  await access(path.join(libDir, 'thumbs', thumbName)).catch(() => { throw new Error(`${modelPath}: missing thumbnail ${thumbName}`); });
  entries.push({ path: modelPath, name: picks.names?.[modelPath] || modelPath, cat: picks.groups?.[modelPath] || 'Characters', url: `/starter-library/models/${modelPath}.glb`, thumb: `/starter-library/thumbs/${thumbName}` });
}
await writeFile(path.join(libDir, 'catalog.json'), JSON.stringify({ name: 'Crate Ship Starter Library', version: picks.savedAt, models: entries }, null, 1) + '\n');
// The AI connector lists these models server-side, so it also gets a plain module it can import.
await writeFile(path.join(libDir, 'catalog.mjs'), '// Generated by scripts/build-starter-library.mjs. Do not edit.\nexport default ' + JSON.stringify(entries.map(({ path: p, name, cat }) => ({ path: p, name, cat }))) + ';\n');
console.log(`Wrote ${entries.length} starter models.`);
